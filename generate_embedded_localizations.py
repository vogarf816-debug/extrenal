#!/usr/bin/env python3
"""Generate a Swift localization table embedded in VESPER's executable.

The source .lproj files stay in the repository for editing, but the app target
uses the generated Swift table so Xcode does not copy separate .lproj folders
into the installed .app bundle. This is packaging/obfuscation only, not secrecy.
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE_DIR = ROOT / "ThreeOneOSFive"
OUTPUT = SOURCE_DIR / "helpers" / "EmbeddedLocalizations.generated.swift"
LOCALES = ("en", "es", "pt-BR", "vi", "zh-Hans")
ENTRY = re.compile(r'^\s*("(?:\\.|[^"\\])*")\s*=\s*("(?:\\.|[^"\\])*")\s*;\s*$')
CHUNK_SIZE = 96


def read_strings(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith(("//", "/*", "*", "*/")):
            continue
        match = ENTRY.match(line)
        if not match:
            raise ValueError(f"Unsupported .strings syntax at {path}:{line_number}")
        key, value = (json.loads(token) for token in match.groups())
        if key in values:
            raise ValueError(f"Duplicate localization key {key!r} at {path}:{line_number}")
        values[key] = value
    if not values:
        raise ValueError(f"No localization entries found in {path}")
    return values


def render() -> str:
    tables: dict[str, dict[str, str]] = {}
    for locale in LOCALES:
        path = SOURCE_DIR / f"{locale}.lproj" / "Localizable.strings"
        tables[locale] = read_strings(path)

    lines = [
        "// Generated by generate_embedded_localizations.py; do not edit by hand.",
        "// Localization strings are embedded in the executable for a cleaner app bundle.",
        "// Base64 is reversible and must not be treated as encryption or secret storage.",
        "import Foundation",
        "",
        "enum EmbeddedLocalizationCatalog {",
        "    private static let encodedTables: [String: String] = [",
    ]
    for locale, table in tables.items():
        payload = json.dumps(table, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
        encoded = base64.b64encode(payload).decode("ascii")
        lines.append(f'        "{locale}": """')
        for start in range(0, len(encoded), CHUNK_SIZE):
            lines.append("        " + encoded[start : start + CHUNK_SIZE])
        lines.append('        """,')
    lines.extend(
        [
            "    ]",
            "",
            "    private static let tables: [String: [String: String]] = {",
            "        var result: [String: [String: String]] = [:]",
            "        for (locale, encoded) in encodedTables {",
            "            guard let data = Data(base64Encoded: encoded, options: .ignoreUnknownCharacters),",
            "                  let object = try? JSONSerialization.jsonObject(with: data),",
            "                  let table = object as? [String: String] else {",
            "                continue",
            "            }",
            "            result[locale] = table",
            "        }",
            "        return result",
            "    }()",
            "",
            "    static func text(for key: String, languageCode: String) -> String? {",
            "        tables[languageCode]?[key]",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated Swift is up to date without writing")
    args = parser.parse_args()
    try:
        generated = render()
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"Localization generation failed: {error}", file=sys.stderr)
        return 1

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"Generated localization file is stale: {OUTPUT}", file=sys.stderr)
            return 1
        print(f"Embedded localization table is up to date: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Generated embedded localization table: {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
